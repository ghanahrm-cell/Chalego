const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, fr, es }

export function translate(lang: Lang, key: MessageKey): string {
  return MESSAGES[lang][key] ?? en[key]
}

export function divisionText(lang: Lang, slug: string, field: 'name' | 'short' | 'tagline', fallback: string) {
  const key = `div.${slug}.${field}` as MessageKey
  return key in en ? translate(lang, key) : fallback
}

